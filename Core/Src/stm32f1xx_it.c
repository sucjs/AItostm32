/*
 * DMA1_Channel3 中断: TIM3_UP 请求的对应通道(硬件固定映射, 见 app_config.h).
 * DShot 逐位写 CCR1 的传输完成/出错都在这里被 HAL 处理.
 *
 * 注意: hdma_tim3 每个 DMA 通道在硬件上唯一, 但该句柄由 signal_output.c
 * 内部持有. 这里以 extern 方式引用同一个对象, 保证中断里操作的就是
 * 正在工作的那个句柄, 而不是另建一个未被 HAL 关联的空句柄.
 */
